#!/usr/bin/env node
/**
 * Parse reference/mockup.html inline script and emit typed data modules + golden ranks.
 * Run: node scripts/extract-mockup.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, '..');
const mockupPath =
  process.env.MOCKUP_PATH ?? path.join(root, 'reference', 'mockup.html');
const outDir = path.join(root, 'src', 'data');
const goldenPath = path.join(root, 'tests', 'golden', 'ranked.json');

const CORE_MARKER = '/* ===== CORE ===== */';
const RANKING_SUFFIX = `
globalThis.__mockupExports__ = undefined;
const total = (subs, w = W) => KEYS.reduce((a, k, i) => a + w[k] * subs[i] / 5, 0);
const ALL = {};
const RANKED = {};
Object.entries(LISTS).forEach(([lk, L]) => {
  const rows = L.products.map((p) => {
    const thin = p[7].filter((x) => /^not stated/i.test(x)).length >= 2;
    const sb = thin
      ? p[5].map((v, i) => (i === 0 || i === 3 ? Math.min(v, 3) : v))
      : p[5];
    return {
      thin,
      id: p[0],
      brand: p[1],
      name: p[2],
      tag: p[3],
      price: p[4],
      subs: sb,
      best: p[6],
      specs: p[7],
      pros: p[8],
      cons: p[9],
      num: p[10],
      X: p[11] || {},
      list: lk,
      total: total(sb),
    };
  });
  rows.sort(
    (a, b) =>
      b.total - a.total || b.subs[2] - a.subs[2] || b.subs[1] - a.subs[1],
  );
  rows.forEach((r, i) => {
    r.rank = i + 1;
    ALL[r.id] = r;
  });
  RANKED[lk] = rows;
});
globalThis.__mockupExports__ = {
  LISTS,
  SRC,
  CATS,
  KWS,
  QKW,
  KFIX,
  CATRANK,
  POSTS,
  TEAM,
  CRIT,
  KEYS,
  W,
  DATE,
  RANKED,
  ALL,
};
`;

function extractScriptSource(html) {
  const match = html.match(/<script>\s*([\s\S]*?)\s*<\/script>\s*<\/body>/i);
  if (!match) throw new Error('No inline <script> found in mockup HTML');
  const full = match[1];
  const coreAt = full.indexOf(CORE_MARKER);
  if (coreAt < 0) throw new Error(`Missing ${CORE_MARKER} in mockup script`);
  return full.slice(0, coreAt) + RANKING_SUFFIX;
}

function runMockupData(scriptSource) {
  const sandbox = { globalThis: {} };
  sandbox.globalThis = sandbox;
  vm.runInNewContext(scriptSource, sandbox, { timeout: 60_000 });
  const out = sandbox.__mockupExports__;
  if (!out) throw new Error('Mockup script did not set __mockupExports__');
  return out;
}

const TYPE_ALIASES = {
  ScoreKey: '(typeof SCORE_KEYS)[number]',
};

function serializeTsConst(name, value, typeName) {
  const json = JSON.stringify(value, null, 2);
  const typeExport = typeName
    ? `\nexport type ${typeName} = ${TYPE_ALIASES[typeName] ?? `typeof ${name}`};\n`
    : '';
  return `export const ${name} = ${json} as const;\n${typeExport}`;
}

function writeDataModules(ctx) {
  fs.mkdirSync(outDir, { recursive: true });

  const scorecardParts = [
    serializeTsConst('CRIT', ctx.CRIT, 'CriterionRow'),
    serializeTsConst('W', ctx.W, 'ScoreWeights'),
    serializeTsConst('SCORE_KEYS', ctx.KEYS, 'ScoreKey'),
  ];
  fs.writeFileSync(
    path.join(outDir, 'scorecard.ts'),
    `/* AUTO-GENERATED by scripts/extract-mockup.mjs — do not edit */\n\n${scorecardParts.join('\n')}`,
  );

  const banner = '/* AUTO-GENERATED by scripts/extract-mockup.mjs — do not edit */\n\n';
  fs.writeFileSync(path.join(outDir, 'meta.ts'), banner + serializeTsConst('SITE_DATE', ctx.DATE));
  fs.writeFileSync(
    path.join(outDir, 'sources.ts'),
    banner + serializeTsConst('SRC', ctx.SRC, 'SourceCatalog'),
  );
  fs.writeFileSync(
    path.join(outDir, 'categories.ts'),
    banner + serializeTsConst('CATS', ctx.CATS, 'CategoryHub'),
  );
  fs.writeFileSync(
    path.join(outDir, 'keywords.ts'),
    banner +
      serializeTsConst(
        'KEYWORDS',
        { KWS: ctx.KWS, QKW: ctx.QKW, KFIX: ctx.KFIX, CATRANK: ctx.CATRANK },
        'KeywordBundle',
      ),
  );
  fs.writeFileSync(
    path.join(outDir, 'posts.ts'),
    banner + serializeTsConst('POSTS', ctx.POSTS, 'PostCatalog'),
  );
  fs.writeFileSync(path.join(outDir, 'team.ts'), banner + serializeTsConst('TEAM', ctx.TEAM, 'TeamRow'));
  fs.writeFileSync(
    path.join(outDir, 'lists.ts'),
    banner + serializeTsConst('LISTS', ctx.LISTS, 'ListCatalog'),
  );

  const index = `/* AUTO-GENERATED by scripts/extract-mockup.mjs */
export { SITE_DATE } from './meta';
export { CRIT, W, SCORE_KEYS, type CriterionRow, type ScoreWeights, type ScoreKey } from './scorecard';
export { SRC, type SourceCatalog } from './sources';
export { CATS, type CategoryHub } from './categories';
export { KEYWORDS, type KeywordBundle } from './keywords';
export { POSTS, type PostCatalog } from './posts';
export { TEAM, type TeamRow } from './team';
export { LISTS, type ListCatalog } from './lists';
`;
  fs.writeFileSync(path.join(outDir, 'index.ts'), index);
}

function writeGolden(RANKED) {
  const golden = {};
  for (const [listKey, rows] of Object.entries(RANKED)) {
    golden[listKey] = rows.map((r) => ({
      id: r.id,
      rank: r.rank,
      total: r.total,
      thin: r.thin,
      subs: r.subs,
    }));
  }
  fs.mkdirSync(path.dirname(goldenPath), { recursive: true });
  fs.writeFileSync(goldenPath, JSON.stringify(golden, null, 2) + '\n');
}

function main() {
  if (!fs.existsSync(mockupPath)) {
    console.error(`Mockup not found: ${mockupPath}`);
    process.exit(1);
  }
  const html = fs.readFileSync(mockupPath, 'utf8');
  const script = extractScriptSource(html);
  const ctx = runMockupData(script);
  if (!ctx.LISTS || !ctx.RANKED) {
    throw new Error('Mockup evaluation did not produce LISTS/RANKED');
  }
  writeDataModules(ctx);
  writeGolden(ctx.RANKED);
  console.log(
    `Wrote src/data/* and ${path.relative(root, goldenPath)} (${Object.keys(ctx.LISTS).length} lists)`,
  );
}

main();